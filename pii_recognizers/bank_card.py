"""银行卡识别规则（BIN 号段 + Luhn 校验）。"""

import re

from pii_engine import PiiRule

_BANK_CARD_RE = re.compile(
    r"(?<!\d)(?:6222|6225|6226|6230|6282|6283|4357|4367|5187|5201|5149|5123|4026|4041"
    r"|4581|4985|5324|5359|5430|5528|5533|5570|5588|6011|6013|6014|6015|6017|6018|6019"
    r"|6020|6021|6022|6023|6024|6025|6026|6027|6028|6029|6030|6031|6032|6033|6034|6035"
    r"|6036|6037|6038|6039|6040|6041|6042|6043|6044|6045|6046|6047|6048|6049|6050|6051"
    r"|6052|6053|6054|6055|6056|6057|6058|6059|6060|6061|6062|6063|6064|6065|6066|6067"
    r"|6068|6069|6070|6071|6072|6073|6074|6075|6076|6077|6078|6079|6080|6081|6082|6083"
    r"|6084|6085|6086|6087|6088|6089|6090|6091|6092|6093|6094|6095|6096|6097|6098|6099)"
    r"\d{12,15}(?!\d)"
)


def luhn_valid(number: str) -> bool:
    if not number.isdigit():
        return False
    total = 0
    for i, ch in enumerate(reversed(number)):
        n = int(ch)
        if i % 2 == 1:
            n *= 2
            if n > 9:
                n -= 9
        total += n
    return total % 10 == 0


def build_rule() -> PiiRule:
    return PiiRule(
        name="cn_bank_card",
        entity_type="CN_BANK_CARD",
        pattern=_BANK_CARD_RE,
        validator=luhn_valid,
    )
